#!/usr/bin/env perl
# Builds the Tag Engine user manual from the Source Distribution build.
#
#   perl UserManual/build-manual.pl [--render pdf|html|none] [--out DIR]
#
# Run it after the Source Distribution build. It:
#   1. reads the Functions palette from Tag Engine.vipb,
#   2. reads each palette VI's description from the built VIs,
#   3. writes palette-reference.adoc (one chapter per palette) next to the
#      hand-written chapters from UserManual/src,
#   4. copies the connector pane images Antidoc made for the project docs
#      (Antidoc-Output/Images), so run the Antidoc project docs first,
#   5. renders the PDF with the Asciidoctor PDF that AsciiDoc for LabVIEW installs.
use strict; use warnings; use utf8;
use FindBin; use lib "$FindBin::Bin/lib";
use palette; use lvrsrc;
use File::Path qw(make_path remove_tree);
use File::Copy qw(copy);
use File::Find qw(find);
use File::Basename qw(dirname basename);
use Getopt::Long;
use Cwd qw(abs_path);
binmode STDOUT, ':encoding(UTF-8)';
binmode STDERR, ':encoding(UTF-8)';

my $root = abs_path("$FindBin::Bin/..");
my %o = (
    vipb   => "$root/Tag Engine.vipb",
    lvproj => "$root/Tag Engine.lvproj",
    images => "$root/Antidoc-Output/Images",
    src    => "$FindBin::Bin/src",
    render => 'pdf',
);
GetOptions(\%o, 'vipb=s', 'lvproj=s', 'images=s', 'src=s', 'out=s', 'render=s', 'version=s')
    or die "usage: build-manual.pl [--render pdf|html|none] [--out DIR] [--version X.Y.Z.W]\n";

# --- Inputs -------------------------------------------------------------------
my $vipb_dir = dirname(canon($o{vipb}));
my $vipb_xml = slurp($o{vipb});
my ($sd_rel) = $vipb_xml =~ m{<Library_Source_Folder>(.*?)</Library_Source_Folder>}
    or die "No <Library_Source_Folder> in $o{vipb}\n";
my $sd = canon("$vipb_dir/$sd_rel");
-d $sd or die "Source Distribution not found: $sd\nBuild it first.\n";
my ($product) = $vipb_xml =~ m{<Product_Name>(.*?)</Product_Name>};
$product //= 'Tag Engine';
my $out = canon($o{out} // dirname($sd) . '/User Manual');
my $version = $o{version} // build_version($o{lvproj});

print "Source Distribution: $sd\nOutput:              $out\nVersion:             $version\n";

my @palettes = palette::read_palettes($o{vipb});
my ($top) = grep { $_->{parent} == -1 } @palettes or die "No top-level palette in $o{vipb}\n";
my %owner_of = owners($sd);   # canonical VI path => [owner chain]

# --- Output folder -----------------------------------------------------------
remove_tree($out) if -d $out;
make_path("$out/images/vi");
copy_tree($o{src}, $out);
my $notices = "$sd/THIRD-PARTY-NOTICES.adoc";
copy($notices, "$out/THIRD-PARTY-NOTICES.adoc") or die "Cannot copy $notices: $!\n" if -f $notices;

# --- Palette reference ---------------------------------------------------------
my @missing_images;
my $adoc = "// Generated by UserManual/build-manual.pl from $product.vipb. Do not edit.\n\n";
$adoc .= palette_chapter($top, "$product Palette", 1);
for my $it (@{ $top->{items} }) {
    next unless $it->{type} eq 'Sub Palette';
    my $p = $palettes[ $it->{sub} ] or next;
    $adoc .= palette_chapter($p, "$it->{name} Palette", 0);
}
write_file("$out/palette-reference.adoc", $adoc);
warn "No connector pane image for: $_ (run the Antidoc project docs first)\n" for @missing_images;

# --- Render ----------------------------------------------------------------------
my ($main) = map { basename($_) } glob("\"$o{src}/*User Manual.adoc\"");
$main or die "No '*User Manual.adoc' in $o{src}\n";
if ($o{render} ne 'none') {
    my $bin = ($ENV{LOCALAPPDATA} // '') . '/Asciidoc For LabVIEW/RubyInstance/bin';
    my $tool = $o{render} eq 'html' ? 'asciidoctor' : 'asciidoctor-pdf';
    -f "$bin/ruby.exe" or die "Asciidoctor not found in $bin (installed by AsciiDoc for LabVIEW).\n";
    my @cmd = ("$bin/ruby.exe", "$bin/$tool", '-a', "revnumber=$version", '-a', 'version-label=Version',
               '-a', 'revdate=' . today(), '-D', $out, "$out/$main");
    print "Rendering $o{render}...\n";
    system(@cmd) == 0 or die "Rendering failed (exit " . ($? >> 8) . ")\n";
}
print "Done: $out\n";

# ==================================================================================

sub palette_chapter {
    my ($p, $title, $is_top) = @_;
    my $id = anchor("palette $title");
    my $s = "[[$id]]\n== $title\n\n";
    $s .= $is_top
        ? "The *$product* palette is in *Functions » Addons » $product*. It holds the VIs most applications need. The subpalettes hold the rest.\n\n"
        : "The *$title* is a subpalette of the $product palette.\n\n";

    # Overview table
    $s .= "[cols=\"1,2\",options=\"header\"]\n|===\n|Item |Summary\n\n";
    for my $it (@{ $p->{items} }) {
        if ($it->{type} eq 'Sub Palette') {
            $s .= "|<<" . anchor("palette $it->{name} Palette") . ",$it->{name}>> (subpalette)\n|" . subpalette_summary($it) . "\n\n";
        } elsif (is_builtin($it)) {
            $s .= "|<<" . anchor("vi $title Property Node") . ",Property Node>>\n|Reads and writes Tag properties through a Tag reference.\n\n";
        } else {
            my $d = description($it);
            $s .= "|<<" . anchor("vi $title $it->{name}") . "," . vi_title($it->{name}) . ">>\n|" . esc(first_sentence($d)) . "\n\n";
        }
    }
    $s .= "|===\n\n";

    # One section per item
    for my $it (@{ $p->{items} }) {
        next if $it->{type} eq 'Sub Palette';
        if (is_builtin($it)) { $s .= property_node_section($title); next; }
        my $path = vi_path($it);
        my $chain = $owner_of{ lc $path } // [];
        $s .= "[[" . anchor("vi $title $it->{name}") . "]]\n=== " . vi_title($it->{name}) . "\n\n";
        my $img = image_for($path, $chain, $it->{name});
        $s .= "image::vi/$img\[" . vi_title($it->{name}) . "]\n\n" if $img;
        $s .= desc_to_adoc(description($it)) . "\n\n";
        my $rel = substr($path, length($sd) + 1);
        $s .= "[.small]#_" . esc(join(':', (map { basename($_) } @$chain), $it->{name})) . "_ (" . esc($rel) . ")#\n\n";
    }
    return $s;
}

sub subpalette_summary {
    my ($it) = @_;
    my $p = $palettes[ $it->{sub} ] or return '';
    my @names = map { is_builtin($_) ? 'Property Node' : vi_title($_->{name}) }
                grep { $_->{type} ne 'Sub Palette' } @{ $p->{items} };
    return esc(join(', ', @names));
}

# The Advanced palette's Property Node: list the Tag class properties.
sub property_node_section {
    my ($title) = @_;
    my $s = "[[" . anchor("vi $title Property Node") . "]]\n=== Property Node\n\n";
    $s .= "LabVIEW's Property Node, placed on this palette for use with Tags. Wire a Tag reference "
        . "(from New Tag or Get Tag) to it to read or write these Tag properties directly:\n\n";
    my $cls = "$sd/Tag/Tag.lvclass";
    return $s . "_(Tag.lvclass not found in the build.)_\n\n" unless -f $cls;
    my $x = slurp($cls);
    $s .= "[cols=\"2,1,1,5\",options=\"header\"]\n|===\n|Property |Read |Write |Description\n\n";
    my @chunks = split /(?=\n\t*<Item Name="[^"]*" Type="Property Definition">)/, $x;
    shift @chunks;
    for my $c (@chunks) {
        my ($indent, $name) = $c =~ /^(\t*)<Item Name="([^"]*)" Type="Property Definition">/m;
        $c =~ s/\n$indent<\/Item>.*//s;   # keep only this definition
        my ($rurl) = $c =~ /<Item Name="Read [^"]*\.vi" Type="VI" URL="([^"]*)"/;
        my ($wurl) = $c =~ /<Item Name="Write [^"]*\.vi" Type="VI" URL="([^"]*)"/;
        my $d = '';
        for my $u (grep { defined } $rurl, $wurl) {
            my $f = resolve_url($cls, $u);
            $d = first_sentence(lvrsrc::read_description($f)) if -f $f && !$d;
        }
        $s .= "|$name |" . ($rurl ? 'Yes' : '') . " |" . ($wurl ? 'Yes' : '') . " |" . esc($d) . "\n";
    }
    return $s . "|===\n\n";
}

sub image_for {
    my ($path, $chain, $name) = @_;
    my $file = join('-', (map { basename($_) } @$chain), $name) . '.png';
    my $src = "$o{images}/$file";
    if (-f $src) {
        copy($src, "$out/images/vi/$file") or die "Cannot copy $src: $!\n";
        return $file;
    }
    push @missing_images, $file;
    return undef;
}

# Turns a VI description into AsciiDoc: "- item" lines become lists, lines that each
# end a sentence keep their line breaks, wrapped lines are joined.
sub desc_to_adoc {
    my ($d) = @_;
    return '_No description._' if $d eq '';
    my @out;
    for my $para (split /\n\s*\n/, $d) {
        my @lines = split /\n/, $para;
        my (@text, @list);
        my $flush_text = sub {
            return unless @text;
            my $sentences = !grep { !/[.:!?)]\s*$/ } @text;
            push @out, (@text > 1 && $sentences) ? join(" +\n", map { esc($_) } @text) : esc(join(' ', @text));
            @text = ();
        };
        my $flush_list = sub {
            return unless @list;
            push @out, join("\n", map { '* ' . esc($_) } @list);
            @list = ();
        };
        for my $l (@lines) {
            if ($l =~ /^\s*[-*]\s+(.*)$/) { $flush_text->(); push @list, $1; }
            else                           { $flush_list->(); push @text, $l; }
        }
        $flush_text->(); $flush_list->();
    }
    return join("\n\n", @out);
}

# Escapes text that AsciiDoc would otherwise interpret.
sub esc {
    my ($t) = @_;
    $t =~ s/\{([\w-]+)\}/\\{$1}/g;    # ${TAG_NAME}: not an attribute reference
    $t =~ s/\|/\\|/g;                 # table cell separator
    $t =~ s/(?<!\w)([*_#`])(?=\S)/\\$1/g;   # stray formatting marks
    return $t;
}

sub first_sentence {
    my ($d) = @_;
    my ($p) = split /\n\s*\n/, $d // '';
    $p //= ''; $p =~ s/\s*\n\s*/ /g;
    my ($s) = $p =~ /^(.*?[.!?])(\s|$)/;
    return $s // $p;
}

sub description { lvrsrc::read_description(vi_path($_[0])) }
sub vi_path     { my ($it) = @_; canon("$vipb_dir/$it->{path}") }
sub vi_title    { (my $n = $_[0]) =~ s/\.(vi|vim|ctl)$//i; $n }
sub is_builtin  { $_[0]{name} =~ /^BUILT_IN_FUNC_/ }
sub anchor      { (my $a = lc $_[0]) =~ s/[^a-z0-9]+/-/g; $a =~ s/^-|-$//g; $a }

# Maps each VI in the build to the chain of libraries/classes that own it.
sub owners {
    my ($dir) = @_;
    my (%member_of, @owners);
    find(sub { push @owners, canon($File::Find::name) if /\.(lvlib|lvclass)$/i }, $dir);
    for my $ow (@owners) {
        my $x = slurp($ow);
        while ($x =~ /<Item Name="[^"]*" Type="(VI|LVClass|Library)" URL="([^"]*)"/g) {
            next if $2 =~ /&lt;|^\//;
            $member_of{ lc canon(resolve_url($ow, $2)) } = $ow;
        }
    }
    my %chain;
    for my $vi (keys %member_of) {
        my @c; my $o = $member_of{$vi};
        while ($o) { unshift @c, $o; $o = $member_of{ lc $o }; }
        $chain{$vi} = \@c;
    }
    return %chain;
}

# LabVIEW member URLs are relative to the owner file as if it were a folder.
sub resolve_url { my ($owner, $url) = @_; canon("$owner/$url") }

sub canon {
    my ($p) = @_;
    $p =~ s{\\}{/}g;
    $p =~ s{/+}{/}g;
    1 while $p =~ s{/(?!\.\.?/)[^/]+/\.\./}{/};
    $p =~ s{/\./}{/}g;
    $p =~ s{/$}{};
    return $p;
}

sub build_version {
    my ($lvproj) = @_;
    my $x = slurp($lvproj);
    my ($bs) = $x =~ m{<Item Name="[^"]*" Type="Source Distribution">(.*?)</Item>}s or return '0.0.0.0';
    my %v = map { $_ => 0 } qw(major minor patch build);
    $v{$1} = $2 while $bs =~ /Bld_version\.(major|minor|patch|build)" Type="Int">(\d+)/g;
    return join('.', @v{qw(major minor patch build)});
}

sub copy_tree {
    my ($from, $to) = @_;
    find(sub {
        return if -d $_;
        (my $rel = $File::Find::name) =~ s{^\Q$from\E/?}{};
        make_path(dirname("$to/$rel"));
        copy($File::Find::name, "$to/$rel") or die "Cannot copy $File::Find::name: $!\n";
    }, $from);
}

sub today { my @t = localtime; sprintf '%04d-%02d-%02d', $t[5] + 1900, $t[4] + 1, $t[3] }
sub slurp { my ($f) = @_; open my $h, '<:raw', $f or die "Cannot read $f: $!\n"; local $/; my $x = <$h>; $x =~ s/^\xEF\xBB\xBF//; $x }
sub write_file { my ($f, $t) = @_; open my $h, '>:encoding(UTF-8)', $f or die "Cannot write $f: $!\n"; print $h $t; close $h }
